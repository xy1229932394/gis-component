const MIN_DISTANCE_DEG = 0.0083

export function formatNumber(num: number | string | null | undefined, decimals = 2): string {
  if (num === null || num === undefined || num === '') {
    return '0'
  }
  const number = typeof num === 'number' ? num : parseFloat(num)
  if (Number.isNaN(number)) {
    return '0'
  }
  return number.toLocaleString('zh-CN', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals
  })
}

export function parseRegion(region: string): RegionInfo {
  if (region.includes('北京市')) {
    return { province: '北京市', city: '北京市辖区', county: '' }
  }
  if (region.includes('上海市')) {
    return { province: '上海市', city: '上海市辖区', county: '' }
  }
  if (region.includes('天津市')) {
    return { province: '天津市', city: '天津市辖区', county: '' }
  }
  if (region.includes('重庆市')) {
    return { province: '重庆市', city: '重庆市辖区', county: '' }
  }

  const parts = region.split(' ')
  if (parts.length >= 3) {
    return { province: parts[0], city: parts[1], county: parts.slice(2).join(' ') }
  }
  if (parts.length === 2) {
    return { province: parts[0], city: parts[1], county: '' }
  }
  return { province: region, city: '', county: '' }
}

export function getCityCoordinates(
  city: string,
  province: string,
  cityCoords: Coordinate = CITY_COORDINATES,
  provinceCoords: Coordinate = PROVINCE_COORDINATES
): [number, number] {
  if (cityCoords[city]) {
    return cityCoords[city]
  }
  if (provinceCoords[province]) {
    return provinceCoords[province]
  }
  return [104.0, 30.0]
}

